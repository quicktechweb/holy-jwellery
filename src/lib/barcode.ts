/** text -> 0/1 bit string (start B + data + checksum + stop) */
export function code128(text: string): string {
  const chars = Array.from(text).map((c) => { const n = c.charCodeAt(0); return n >= 32 && n <= 126 ? c : '?'; });
  const codes = [104];
  let sum = 104;
  chars.forEach((c, i) => { const v = c.charCodeAt(0) - 32; codes.push(v); sum += v * (i + 1); });
  codes.push(sum % 103, 106);
  return codes.map((c) => BARS[c]).join('');
}

/** consecutive black bars gulo merge kore (x, width) list */
export function barRuns(bits: string): { x: number; w: number }[] {
  const runs: { x: number; w: number }[] = [];
  let i = 0;
  while (i < bits.length) {
    if (bits[i] === '1') { let j = i; while (bits[j] === '1') j++; runs.push({ x: i, w: j - i }); i = j; } else i++;
  }
  return runs;
}

/** print window er jonno plain SVG string */
export function barcodeSvgString(text: string, heightPx: number): string {
  const bits = code128(text);
  const rects = barRuns(bits).map((r) => `<rect x="${r.x}" y="0" width="${r.w}" height="1" />`).join('');
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${bits.length} 1" preserveAspectRatio="none" style="width:100%;height:${heightPx}px;display:block" fill="#000">${rects}</svg>`;
}
